// Writes lib/brandLogos.ts: the logo of each connector in Conexiones, taken
// from simple-icons (CC0, a devDependency) so the app carries only these and
// not the whole set. Run it after adding a connector:
//   node apps/mobile/scripts/brand-logos.mjs
// A connector simple-icons doesn't have shows its initial instead.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as icons from 'simple-icons';

// Connector id → simple-icons slug.
const SLUGS = {
  google: 'google',
  googlebusiness: 'google',
  searchconsole: 'googlesearchconsole',
  analytics: 'googleanalytics',
  youtube: 'youtube',
  instagram: 'instagram',
  tiktok: 'tiktok',
  buffer: 'buffer',
  xero: 'xero',
  stripe: 'stripe',
  paypal: 'paypal',
  square: 'square',
  sumup: 'sumup',
  mailchimp: 'mailchimp',
  brevo: 'brevo',
  semrush: 'semrush',
  calendly: 'calendly',
  calcom: 'caldotcom',
  typeform: 'typeform',
  hubspot: 'hubspot',
  zendesk: 'zendesk',
  notion: 'notion',
  airtable: 'airtable',
  linear: 'linear',
  asana: 'asana',
  clickup: 'clickup',
  todoist: 'todoist',
  miro: 'miro',
  wix: 'wix',
  wordpress: 'wordpress',
  webflow: 'webflow',
  squarespace: 'squarespace',
  dropbox: 'dropbox',
  zoom: 'zoom',
  zapier: 'zapier',
  make: 'make',
  // The AI accounts (ia/[provider]): Claude through Anthropic (a key or a subscription), Claude in Google Cloud.
  'ai-anthropic': 'claude',
  'ai-claude': 'claude',
  'ai-vertex': 'googlecloud',
};

// Not in simple-icons (its maker asked for it to be removed), drawn here: four squares.
const OWN = {
  microsoft: { path: 'M2 2h9.5v9.5H2zM12.5 2H22v9.5h-9.5zM2 12.5h9.5V22H2zM12.5 12.5H22V22h-9.5z', hex: '0078D4' },
};

const bySlug = Object.fromEntries(Object.values(icons).filter((i) => i && i.slug).map((i) => [i.slug, i]));
const out = { ...OWN };
for (const [id, slug] of Object.entries(SLUGS)) {
  const icon = bySlug[slug];
  if (!icon) throw new Error(`simple-icons has no «${slug}» (for ${id})`);
  out[id] = { path: icon.path, hex: icon.hex };
}

const lines = Object.keys(out)
  .sort()
  .map((id) => `  ${JSON.stringify(id)}: { hex: '#${out[id].hex}', path: ${JSON.stringify(out[id].path)} },`);
const file = `// GENERATED by scripts/brand-logos.mjs from simple-icons (CC0). Do not edit by hand.
// Each connector's logo: one SVG path on a 24×24 box, and its brand colour.

export const BRAND_LOGOS: Record<string, { hex: string; path: string }> = {
${lines.join('\n')}
};
`;
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, '..', 'lib', 'brandLogos.ts'), file);
console.log(`${Object.keys(out).length} logos → lib/brandLogos.ts`);
